/**
 * Safely retrieves a nested translation by dot-path.
 * Fallback priority: selected language -> English -> key path
 */
export function getNestedTranslation(lang, path, params = {}) {
  const currentDict = translations[lang] || translations.en;
  const fallbackDict = translations.en;

  const resolve = (dict, keyPath) => {
    return keyPath.split(".").reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), dict);
  };

  let value = resolve(currentDict, path);
  if (value === undefined) {
    value = resolve(fallbackDict, path);
  }

  if (value === undefined) {
    return path;
  }

  if (typeof value === "string") {
    // Interpolate {param}
    return value.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? params[k] : `{${k}}`));
  }

  return value;
}
